const messageKeyByEnglish = new Map(Object.entries(messages.EN).map(([key, value]) => [value, key]))
const localizedMessages: Record<Language, Record<string, string>> = messages

export function translateText(language: Language, text: string) {
  const messageKey = messageKeyByEnglish.get(text)
  return interfaceText[text]?.[language] ?? (messageKey ? localizedMessages[language][messageKey] : undefined) ?? text
}

export function localeCode(language: Language) {
  return language === 'RW' ? 'rw-RW' : language === 'FR' ? 'fr-FR' : 'en'
}

